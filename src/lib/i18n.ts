export function localizedPath(locale: Locale, path: string) {
  if (locale === "ru") return path;
  if (path === "/") return "/en";
  return `/en${path}`;
}

export function oppositeLocale(locale: Locale): Locale {
  return locale === "ru" ? "en" : "ru";
}
